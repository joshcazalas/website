export function pixelWidth(text: string, size: number) { return (text.length * 6 - 1) * size; }
export function pixelText(parent: Container, text: string, x: number, y: number, size: number, color = 0x282a27, centered = false) {
  const graphic = new Graphics();
  const left = centered ? x - pixelWidth(text, size) / 2 : x;
  for (let i = 0; i < text.length; i++) {
    const rows = (alphabet[text[i].toUpperCase()] ?? alphabet[' ']).split('/');
    rows.forEach((row, iy) => [...row].forEach((on, ix) => {
      if (on === '1') graphic.rect(left + (i * 6 + ix) * size, y + iy * size, size - Math.min(0.6, size * 0.06), size - Math.min(0.6, size * 0.06));
    }));
  }
  graphic.fill(color);
  parent.addChild(graphic);
  return graphic;
}
